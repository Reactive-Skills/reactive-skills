#!/usr/bin/env node
/**
 * scripts/sync-changelog.js
 *
 * Automatically synchronizes release history from packages/runtime/CHANGELOG.md to:
 * 1. Root CHANGELOG.md (for GitHub repository visitors)
 * 2. apps/site/src/infrastructure/content/docs/changelog.js (for the documentation site)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const RUNTIME_CHANGELOG = path.join(ROOT_DIR, 'packages', 'runtime', 'CHANGELOG.md');
const ROOT_CHANGELOG = path.join(ROOT_DIR, 'CHANGELOG.md');
const SITE_CHANGELOG = path.join(ROOT_DIR, 'apps', 'site', 'src', 'infrastructure', 'content', 'docs', 'changelog.js');

if (!fs.existsSync(RUNTIME_CHANGELOG)) {
  console.error(`❌ Authoritative changelog not found: ${RUNTIME_CHANGELOG}`);
  process.exit(1);
}

const rawMarkdown = fs.readFileSync(RUNTIME_CHANGELOG, 'utf8');

// 1. Sync to Root CHANGELOG.md
fs.writeFileSync(ROOT_CHANGELOG, rawMarkdown, 'utf8');
console.log(`[sync-changelog] Synced root ${path.relative(ROOT_DIR, ROOT_CHANGELOG)}`);

// 2. Parse Markdown Sections
// Expects: ## [X.Y.Z] - YYYY-MM-DD followed by bullet points
const versionRegex = /^##\s*\[([^\]]+)\](?:\s*-\s*([0-9-]+))?/gm;
const sections = [];
const matches = [];

let match;
while ((match = versionRegex.exec(rawMarkdown)) !== null) {
  matches.push({
    version: match[1],
    date: match[2] || '',
    index: match.index,
  });
}

for (let i = 0; i < matches.length; i++) {
  const current = matches[i];
  const next = matches[i + 1];
  const sectionContent = next
    ? rawMarkdown.slice(current.index, next.index)
    : rawMarkdown.slice(current.index);

  const lines = sectionContent
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.startsWith('- ') || l.startsWith('* '));

  const items = lines.map((l) => l.replace(/^[-*]\s+/, '').replace(/\s*\([a-f0-9]{7,}\)$/, ''));

  if (items.length > 0) {
    const slugId = `v${current.version.replace(/\./g, '-')}`;
    const heading = current.date ? `v${current.version} (${current.date})` : `v${current.version}`;

    sections.push({
      id: slugId,
      heading,
      blocks: [
        {
          type: 'list',
          items,
        },
      ],
    });
  }
}

// 3. Generate site JS module
const siteContent = `/** @type {import('@/contracts/types').DocPage} */
// AUTO-GENERATED by scripts/sync-changelog.js — DO NOT EDIT DIRECTLY
export const changelog = {
  slug: 'changelog',
  title: 'Changelog',
  summary: 'Full release history and architectural evolution of the Reactive Skills Architecture (RSA).',
  category: 'Reference',
  href: '/docs/changelog',
  sections: ${JSON.stringify(sections, null, 2)},
  relatedPages: [
    { title: 'AXI CLI reference (Preferred)', href: '/docs/axi' },
    { title: 'Quickstart', href: '/docs/quickstart' },
    { title: 'Troubleshooting guide', href: '/docs/troubleshooting' },
  ],
};
`;

fs.writeFileSync(SITE_CHANGELOG, siteContent, 'utf8');
console.log(`[sync-changelog] Generated ${sections.length} release sections in ${path.relative(ROOT_DIR, SITE_CHANGELOG)}`);
